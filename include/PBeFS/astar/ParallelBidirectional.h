/** @file
 * Header file for the class template ParallelBidirectional, the
 * front-to-end bidirectional search whose two directions run at once on
 * two workers of an Executor, sharing the table of the nodes and the
 * incumbent: PNBA* of Rios and Chaimowicz (2011), the parallel version of
 * the NBA* of Pijls and Post (2009), and, with the same scheme, the
 * parallel versions of BAE*, MM and the bidirectional Dijkstra's
 * algorithm.
 *
 * The worker of the direction D runs the best-first search of D on its own
 * open list and writes only the fields of D of the nodes: \f$ g_D \f$, the
 * parent, the operator and the flag closed_D; it reads those of the other
 * direction, which the other worker writes, and both lower the incumbent
 * \f$ U \f$ under a lock. A state generated by a worker with a finite
 * \f$ g \f$ of the other direction is a path: since both workers write
 * their \f$ g \f$ and then read the other one, with sequentially consistent
 * accesses, a state reached by both is seen by at least one of them (the
 * argument of Dekker's mutual exclusion), and no meeting is missed.
 *
 * After each expansion a worker publishes the least keys of its open list
 * (f, g and the priority of the algorithm); with consistent heuristics
 * each of them never decreases, since a node popped has a key not smaller
 * than the least one and its children not smaller than its own, so that a
 * value read by the other worker, however old, is a lower bound on the
 * least key of the nodes open or being expanded there. The bound of the
 * algorithm [see BiBestFirst.h] computed from the two published records is
 * then a lower bound on \f$ C^* \f$, and a worker stops both when
 * \f$ U \f$ is not larger, or when its open list is empty. NBA* expands
 * by \f$ f_D \f$ and does not expand a node x, which it closes, when
 * \f$ f_D( x ) \geq U \f$ or \f$ g_D( x ) + F_{\bar D} - h_{\bar D}( x )
 * \geq U \f$, \f$ F_{\bar D} \f$ being the least \f$ f \f$ published by the
 * other direction [Pijls and Post, 2009, section 3]: both rejections need
 * consistent heuristics, as does this parallel scheme, and the
 * constructor refuses BidirectionalOptions::consistent false.
 *
 * \author Donato Meoli \n
 *         Dipartimento di Informatica \n
 *         Università di Pisa \n
 *
 * \copyright &copy; by Donato Meoli
 */
