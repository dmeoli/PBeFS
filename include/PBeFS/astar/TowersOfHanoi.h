/*-------------------------- CLASS TowersOfHanoi ---------------------------*/
/*--------------------------------------------------------------------------*/
/// the Towers of Hanoi with four pegs and D disks
/** The state is a word, the peg of the disk d in its bits 2 d and 2 d + 1;
 * the heuristic is 0, the pattern databases being given by HanoiPDB and
 * PDBDomain [see PermutationPDB.h]. The operator of a move of the disk d
 * from the peg a is 4 d + a; the successors of an OperatorDomain skip the
 * move of the disk just moved back to its peg, those of a tree search every
 * move of the disk just moved, since two moves of the same disk in a row
 * are matched by one or none. The moves are generated by the peg of the
 * disk, then by the peg it goes to. */

template< int D >
class TowersOfHanoi {

 static_assert( ( D >= 1 ) && ( D <= 32 ) , "TowersOfHanoi: 1 to 32 disks" );

/*------------------------ PUBLIC PART OF THE CLASS ------------------------*/

 public:

/*------------------------------ PUBLIC TYPES ------------------------------*/

 using state_type = std::uint64_t;                    ///< the pegs
 using cost_type = int;                               ///< the cost type

/*------------------------------ CONSTRUCTOR -------------------------------*/
 /// constructor, taking the start and the goal

 TowersOfHanoi( state_type start , state_type goal )
  : f_start( start & mask() ) , f_goal( goal & mask() ) {}

/*------------------------- METHODS OF THE DOMAIN --------------------------*/

 [[nodiscard]] state_type initial_state( void ) const noexcept {
  return( f_start );
  }

 [[nodiscard]] bool is_goal( state_type s ) const noexcept {
  return( s == f_goal );
  }

 [[nodiscard]] static std::uint64_t hash( state_type s ) noexcept {
  return( ADS::splitmix64( s ) );
  }

 [[nodiscard]] static cost_type heuristic( state_type ) noexcept {
  return( 0 );
  }

 template< class F >
 void for_each_successor( state_type s , cost_type h , F && f ) const {
  moves( s , no_op , false , [ & ]( state_type t , std::uint8_t ) {
   f( t , 1 , cost_type( 0 ) );
   } );
  ( void ) h;
  }

 /// the successors but the move of the disk of op back to its peg
 template< class F >
 void for_each_successor( state_type s , cost_type , std::uint8_t op ,
                          F && f ) const {
  moves( s , op , false , [ & ]( state_type t , std::uint8_t o ) {
   f( t , 1 , cost_type( 0 ) , o );
   } );
  }

 /// the successors but the moves of the disk of op
 template< class F >
 void for_each_tree_successor( state_type s , cost_type , std::uint8_t op ,
                               F && f ) const {
  moves( s , op , true , [ & ]( state_type t , std::uint8_t o ) {
   f( t , 1 , cost_type( 0 ) , o );
   } );
  }

/*---------------------- FEATURES FOR ZOBRIST HASHING ----------------------*/

 [[nodiscard]] static constexpr std::size_t num_features( void ) noexcept {
  return( 4 * D );
  }

 template< class F >
 void for_each_feature( state_type s , F && f ) const {
  for( int d = 0 ; d < D ; ++d )
   f( std::size_t( 4 * d + ( ( s >> ( 2 * d ) ) & 3 ) ) );
  }

 template< class F >
 void for_each_feature_change( state_type s , state_type t , F && f ) const {
  const std::uint64_t x = s ^ t;
  if( x == 0 )
   return;
  const int d = std::countr_zero( x ) / 2;
  f( std::size_t( 4 * d + ( ( s >> ( 2 * d ) ) & 3 ) ) );
  f( std::size_t( 4 * d + ( ( t >> ( 2 * d ) ) & 3 ) ) );
  }

/*------------------------------ OTHER HASHES ------------------------------*/
 /// the perfect hash: the state

 [[nodiscard]] static std::uint64_t perfect_hash( state_type s ) noexcept {
  return( s );
  }

/*-------------------------------- HELPERS ---------------------------------*/
 /// the goal

 [[nodiscard]] state_type goal( void ) const noexcept { return( f_goal ); }

/*- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/
 /// the bits of the D disks

 [[nodiscard]] static constexpr std::uint64_t mask( void ) noexcept {
  return( D == 32 ? ~std::uint64_t( 0 )
                  : ( std::uint64_t( 1 ) << ( 2 * D ) ) - 1 );
  }

/*- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/
 /// the four pegs in text, each "(p)" followed by its disks from 1 (the
 /// smallest) to D, as in the instances of Siag et al.; reads one state
 /// from in, and throws std::invalid_argument if it is not that

 [[nodiscard]] static state_type read( std::istream & in ) {
  state_type s = 0;
  std::uint64_t seen = 0;
  std::string tok;
  int peg = -1 , pegs = 0;
  for( ; ; ) {
   const auto pos = in.tellg();
   if( ! ( in >> tok ) )
    break;
   if( tok.front() == '(' ) {
    if( pegs == 4 ) {                    // the next state
     in.seekg( pos );
     break;
     }
    peg = std::stoi( tok.substr( 1 ) );
    if( ( peg < 0 ) || ( peg > 3 ) )
     throw( std::invalid_argument( "TowersOfHanoi::read: bad peg" ) );
    ++pegs;
    continue;
    }
   const int d = std::stoi( tok ) - 1;
   if( ( peg < 0 ) || ( d < 0 ) || ( d >= D ) || ( ( seen >> d ) & 1u ) )
    throw( std::invalid_argument( "TowersOfHanoi::read: bad disk" ) );
   seen |= std::uint64_t( 1 ) << d;
   s |= std::uint64_t( peg ) << ( 2 * d );
   }
  if( seen != ( std::uint64_t( 1 ) << D ) - 1 )
   throw( std::invalid_argument( "TowersOfHanoi::read: missing disks" ) );
  return( s );
  }

/*- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/
 /// the state in the text of read()

 [[nodiscard]] static std::string write( state_type s ) {
  std::string t;
  for( int p = 0 ; p < 4 ; ++p ) {
   t += ( p ? " (" : "(" ) + std::to_string( p ) + ")";
   for( int d = D - 1 ; d >= 0 ; --d )
    if( int( ( s >> ( 2 * d ) ) & 3 ) == p )
     t += " " + std::to_string( d + 1 );
   }
  return( t );
  }

/*----------------------- PRIVATE PART OF THE CLASS ------------------------*/

 private:

 // calls f( t , op_t ) for the moves of s, but those of the disk of op
 // (tree) or that of the disk of op back to its peg (not tree)
 template< class F >
 static void moves( state_type s , std::uint8_t op , bool tree , F && f ) {
  unsigned top[ 4 ];
  hanoi_tops( s , D , top );
  const int last = op == no_op ? -1 : op / 4 , back = op % 4;
  for( unsigned a = 0 ; a < 4 ; ++a ) {
   const unsigned d = top[ a ];
   if( ( d == unsigned( D ) ) || ( int( d ) == last && tree ) )
    continue;
   for( unsigned b = 0 ; b < 4 ; ++b )
    if( ( b != a ) && ( top[ b ] > d ) &&
        ! ( ( int( d ) == last ) && ( int( b ) == back ) ) )
     f( s ^ ( std::uint64_t( a ^ b ) << ( 2 * d ) ) ,
        std::uint8_t( 4 * d + a ) );
   }
  }

 state_type f_start;                            ///< the start
 state_type f_goal;                             ///< the goal

 };  // end( class( TowersOfHanoi ) )

/*--------------------------------------------------------------------------*/
/*---------------------------- CLASS HanoiSpace ----------------------------*/
/*--------------------------------------------------------------------------*/
/// the abstract space of the disks lo , ... , lo + k - 1 of the Towers of
/// Hanoi with four pegs
/** An AbstractSpace [see AbstractionPDB.h] of \f$ 4^k \f$ states, the rank
 * of a state being the pegs of the k disks, two bits each, the disk lo in
 * the lowest; its goal is the image of the goal of the puzzle, and its
 * moves are those of its disks, each its own inverse. */

class HanoiSpace {

 public:

 /// the space of the k disks from lo of a puzzle whose goal is goal;
 /// throws std::invalid_argument unless 1 <= k <= 16
 HanoiSpace( unsigned lo , unsigned k , std::uint64_t goal )
  : f_lo( lo ) , f_k( k ) {
  if( ( k == 0 ) || ( k > 16 ) || ( lo + k > 32 ) )
   throw( std::invalid_argument( "HanoiSpace: 1 to 16 disks" ) );
  f_goal = rank( goal );
  }

 /// the rank of the image of the state s of the puzzle
 [[nodiscard]] std::uint64_t rank( std::uint64_t s ) const noexcept {
  return( ( s >> ( 2 * f_lo ) ) & ( ( std::uint64_t( 1 ) << ( 2 * f_k ) ) -
                                    1 ) );
  }

 [[nodiscard]] std::uint64_t size( void ) const noexcept {
  return( std::uint64_t( 1 ) << ( 2 * f_k ) );
  }

 template< class F >
 void for_each_goal( F && f ) const { f( f_goal ); }

 template< class F >
 void for_each_predecessor( std::uint64_t r , F && f ) const {
  unsigned top[ 4 ];
  hanoi_tops( r , f_k , top );
  for( unsigned a = 0 ; a < 4 ; ++a ) {
   const unsigned d = top[ a ];
   if( d == f_k )
    continue;
   for( unsigned b = 0 ; b < 4 ; ++b )
    if( ( b != a ) && ( top[ b ] > d ) )
     f( r ^ ( std::uint64_t( a ^ b ) << ( 2 * d ) ) , 1u );
   }
  }

 /// the first disk
 [[nodiscard]] unsigned lo( void ) const noexcept { return( f_lo ); }

 /// the disks
 [[nodiscard]] unsigned k( void ) const noexcept { return( f_k ); }

 private:

 unsigned f_lo;                                 ///< the first disk
 unsigned f_k;                                  ///< the disks
 std::uint64_t f_goal = 0;                      ///< the abstract goal

 };  // end( class( HanoiSpace ) )

