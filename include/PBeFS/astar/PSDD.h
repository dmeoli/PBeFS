/** @file
 * Header file for the searches by parallel structured duplicate detection
 * on the nblocks of an NBlockDomain: PSDD, the layered search of Zhou and
 * Hansen (AAAI 2007), BFPSDD, its best-first version of Burns et al. (JAIR
 * 2010), and IDPSDD and DynamicBoundedPSDD, which give PSDD its bound.
 *
 * Both searches go by layers. A layer is a set of nblocks, which the
 * workers acquire one at a time, as in SafePBNF, when no nblock in use is
 * in their interference scope [see NBlockMap.h], so that a worker inserts
 * the children of its nodes in the lists of its duplicate detection scope
 * with no lock; when no nblock of the layer is left and none is in use,
 * the last worker to release one builds the next layer, while the others
 * wait. With the notation of the page "Best-first search and A*" of the
 * documentation, \f$ z \f$ the incumbent, \f$ \beta \f$ the bound (the
 * nodes of larger \f$ f \f$ are pruned, the least of their \f$ f \f$ being
 * kept for IDPSDD), \f$ \lambda \f$ the value of the layer, \f$ p \f$ the
 * workers, \f$ m \f$ the multiplier and \f$ e \f$ the minimum number of
 * expansions:
 *
 * \code{.unparsed}
 *  1  procedure THREADSEARCH()                        ▷ on each worker
 *  2     b ← nil
 *  3     loop
 *  4        b ← NEXTNBLOCK(b);  if b = nil then return
 *  5        k ← 0
 *  6        while OPEN(b) has a node of f < z do
 *  7           if BFPSDD, k ≥ e and the least f of OPEN(b) is above λ then
 *                 break
 *  8           u ← the first node of OPEN(b), removed;  close u;  k ← k + 1
 *  9           for each successor v of u, g' ← g(u) + c(u, v) do
 * 10              if g' + h(v) > β or g' + h(v) ≥ z then continue
 * 11              if v ∉ CLOSED(b(v)) or g' < g(v) then
 * 12                 g(v) ← g';  parent(v) ← u;  v is not closed
 * 13                 if v is a goal then z ← min(z, g'), recording v
 * 14                 else push v in NEXT(b(v))
 * 15  procedure NEXTNBLOCK(b)
 * 16     lock the graph
 * 17     if b ≠ nil then release b, freeing the nblocks of the layer
 *           that no nblock in use interferes with any more
 * 18     while no nblock of the layer is free do
 * 19        if no nblock is in use then NEXTLAYER()
 * 20        if done then return nil
 * 21        if some nblock is in use then sleep until woken
 * 22     b ← a free nblock of the layer;  acquire b;  return b
 * 23  procedure NEXTLAYER()
 * 24     if PSDD then
 * 25        the layer: the nblocks with nodes of f < z in NEXT, whose
 *              NEXT becomes OPEN
 * 26     else
 * 27        λ ← the least f < z of the OPEN lists
 * 28        the layer: the m p nblocks of least f < z in OPEN, and all
 *              those whose least f is λ
 * 29     if the layer is empty then done ← true
 * 30     wake all
 * \endcode
 *
 * In PSDD every nblock has two OPEN lists, OPEN for the layer and NEXT for
 * the following one, so that the layers are those of breadth-first search,
 * each made of the nodes generated by the expansions of the one before;
 * in BFPSDD, NEXT is OPEN, and the layers follow the least \f$ f \f$ of the
 * nblocks, as in best-first search. The goal test is done at the
 * generation (line 13), and the search does not stop at the first goal: it
 * ends when no OPEN list holds a node of \f$ f < z \f$ (line 29), so that
 * \f$ z \f$ is the cost of a path of least cost among those whose nodes
 * have \f$ f \le \beta \f$, whatever the costs of the edges; with costs all
 * equal to 1, a goal generated in the layer \f$ d \f$ has \f$ z = d + 1 \f$,
 * no node of the next layer has a smaller \f$ f \f$, and the search ends
 * with that layer, as the breadth-first heuristic search of Zhou and
 * Hansen (2006) on which PSDD is built.
 *
 * \author Donato Meoli \n
 *         Dipartimento di Informatica \n
 *         Università di Pisa \n
 *
 * \copyright &copy; by Donato Meoli
 */
