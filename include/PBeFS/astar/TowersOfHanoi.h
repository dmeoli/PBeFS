/** @file
 * Header file for the class template TowersOfHanoi, which implements the
 * Domain concept [see Domain.h] for the Towers of Hanoi with four pegs and
 * any start and goal, and for its additive pattern databases, the abstract
 * space HanoiSpace of a range of disks and the heuristic HanoiPDB, after
 * Felner, Korf and Hanan (JAIR 2004).
 *
 * A state places D disks, 0 the smallest, on the pegs 0 to 3, two bits per
 * disk, the disks of a peg being stacked by size; a move takes the top disk
 * of a peg to another peg whose top disk is larger, or which is empty, at
 * cost 1. The abstraction of a range of disks keeps only them, the others
 * being removed, so that a move of the puzzle is a move of the abstraction
 * if it moves a disk of the range and a loop otherwise; the moves are their
 * own inverses, the distance in the abstraction is at most that in the
 * puzzle, and since a move moves one disk the sum of the tables of disjoint
 * ranges is admissible and consistent. The instances of Siag et al. (ECAI
 * 2024) have D = 20, and their heuristic is the sum of the tables of the 4
 * smallest and of the 16 largest disks.
 *
 * \author Donato Meoli \n
 *         Dipartimento di Informatica \n
 *         Università di Pisa \n
 *
 * \copyright &copy; by Donato Meoli
 */
