/*----------------------------- CLASS HanoiPDB -----------------------------*/
/*--------------------------------------------------------------------------*/
/// the additive pattern databases of the Towers of Hanoi with four pegs
/** The sum of the tables of consecutive ranges of disks, given by their
 * sizes from the smallest disk (4 and 16 for the heuristic of Siag et al.
 * on 20 disks), one byte per entry, built on threads workers or read from
 * a cache directory. */

class HanoiPDB {

 public:

 /// the tables of the ranges of sizes ks (summing to the disks of the
 /// puzzle) for the goal goal
 HanoiPDB( const std::vector< unsigned > & ks , std::uint64_t goal ,
           unsigned threads = 0 , const std::string & cache = "" ) {
  unsigned lo = 0;
  for( unsigned k : ks ) {
   HanoiSpace sp( lo , k , goal );
   char hex[ 17 ];
   std::snprintf( hex , sizeof( hex ) , "%016llx" ,
                  static_cast< unsigned long long >( sp.rank( goal ) ) );
   const std::string name = "hanoi-" + std::to_string( lo ) + "-" +
                            std::to_string( k ) + "-" + hex + ".pdb";
   const std::uint64_t key = ADS::splitmix64( ( std::uint64_t( lo ) << 40 ) ^
                                              ( std::uint64_t( k ) << 32 ) ^
                                              sp.rank( goal ) );
   v_tables.push_back( AbstractionTable< 8 >::cached(
    cache , name , key , sp.size() , [ & ] {
     return( abstract_distances( sp , threads ) );
     } ) );
   v_spaces.push_back( sp );
   lo += k;
   }
  }

 /// the value of the state s
 [[nodiscard]] unsigned operator()( std::uint64_t s ) const noexcept {
  unsigned h = 0;
  for( std::size_t i = 0 ; i < v_spaces.size() ; ++i )
   h += v_tables[ i ][ v_spaces[ i ].rank( s ) ];
  return( h );
  }

 /// the tables
 [[nodiscard]] const std::vector< AbstractionTable< 8 > > & tables( void )
  const noexcept {
  return( v_tables );
  }

 private:

 std::vector< HanoiSpace > v_spaces;            ///< the ranges
 std::vector< AbstractionTable< 8 > > v_tables;   ///< their tables

 };  // end( class( HanoiPDB ) )

