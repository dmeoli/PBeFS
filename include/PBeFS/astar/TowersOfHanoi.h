/// the smallest disk on each of the four pegs of the k disks of x (two bits
/// each, the disk 0 in the lowest), or k for an empty peg

inline void hanoi_tops( std::uint64_t x , unsigned k , unsigned top[ 4 ] )
 noexcept
{
 const std::uint64_t used = k >= 32 ? ~std::uint64_t( 0 )
                                    : ( std::uint64_t( 1 ) << ( 2 * k ) ) - 1;
 for( unsigned p = 0 ; p < 4 ; ++p ) {
  // the fields of x equal to p have both bits of x ^ p p ... p clear
  const std::uint64_t y = x ^ ( 0x5555555555555555ULL * p );
  const std::uint64_t eq = ~( y | ( y >> 1 ) ) & 0x5555555555555555ULL &
                           used;
  top[ p ] = eq ? unsigned( std::countr_zero( eq ) ) / 2 : k;
  }
 }

